"""One manufactured chest surface for the three NYX tiers, with a common depth datum."""
import math
from mathutils import Vector


def build_cuirass(g, tier, upper, lower, width, ceramic, trim, dark, metal, signal):
    light = tier == 0
    heavy = tier == 2
    name = ['VEIL', 'SHADE', 'WRAITH'][tier]
    bottom = lower + .012
    top = upper - .012
    height = top - bottom
    half = width * .97
    # A broad transverse arc bridges the sternum and chest. It never traces
    # individual breast contours or samples a separate surface for each plate.
    roll = .028 if heavy else .024
    def envelope(y):
        samples=[]
        for u in [-.94,-.7,-.45,0,.45,.7,.94]:
            hit=g.tree.ray_cast(Vector((half*u,y,.6)),Vector((0,0,-1)),1.2)[0]
            # Lower corners taper inside the rib cage: no body exists at the
            # full shoulder width there, so that sample needs no clearance.
            if hit is not None:samples.append(hit.z+roll*u*u)
        if not samples:raise RuntimeError('Missing cuirass cross-section')
        return max(samples)+(.008 if light else .014)
    z0, z1 = envelope(bottom), envelope(top)
    def crown(t):return min(1,t/.25,(1-t)/.25)
    bow = .004
    for i in range(1,40):
        t = i/40
        required = envelope(bottom + t*height)
        bow = max(bow,(required-(z0*(1-t)+z1*t))/crown(t))
    def sample(x,y,offset=0):
        t = (y-bottom)/height
        z = z0*(1-t)+z1*t+bow*crown(t)-roll*(abs(x/half) if light else (x/half)**2)
        if light:z += roll*.25  # maximum difference between the fitted arc and side facets
        # Wraith's central keel is part of the shell, not another stacked plate.
        if heavy:z += .004*max(0,1-abs(x)/.045)
        return Vector((x,y,z+offset))
    outline=[(-.030,top-.022),(-half*.73,top),(-half,top-.051),
             (-half*.91,bottom+.060),(-half*.64,bottom+.008),(0,bottom),
             (half*.64,bottom+.008),(half*.91,bottom+.060),
             (half,top-.051),(half*.73,top),(.030,top-.022)]
    if light:
        outline=[(-.018,top-.026),(-half*.60,top),(-half,top-.068),
                 (-half*.76,bottom+.068),(-half*.38,bottom+.018),(0,bottom),
                 (half*.38,bottom+.018),(half*.76,bottom+.068),
                 (half,top-.068),(half*.60,top),(.018,top-.026)]
    outline=[Vector((a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t))
             for a,b in zip(outline,outline[1:]+outline[:1]) for t in [0,.25,.5,.75]]
    center=sum(outline,Vector((0,0)))/len(outline)
    count=len(outline);vs=[]
    # A 2 mm perimeter bevel, followed by a continuously curved face.
    for scale,offset in [(1,0),(.975,.002),(.88,.002),(.72,.002),(.54,.002),(.36,.002),(.18,.002)]:
        for uv in outline:
            p=center+(uv-center)*scale
            vs.append(sample(*p,offset))
    vs.append(sample(*center,.002))
    fs=[(r*count+j,r*count+(j+1)%count,(r+1)*count+(j+1)%count,(r+1)*count+j)
        for r in range(6) for j in range(count)]
    fs += [(6*count+j,6*count+(j+1)%count,len(vs)-1) for j in range(count)]
    # A rigid manufactured plate follows the upper torso as a unit. Fitting its
    # edge to shoulder/abdomen weights can twist it into an accordion in profile.
    start=len(g.objects)
    g.mesh(name+' / continuous chest shell',vs,fs,ceramic,rigid='Spine2',thickness=.004 if light else .009 if heavy else .006,thickness_offset=-1)
    edge=[sample(*(center+(uv-center)*.955),.003) for uv in outline]
    g.tube(name+' / chest edge binding',edge+[edge[0]],.0015 if heavy else .0011,trim,rigid='Spine2')
    # Flush channels share exactly the shell surface; their depth never accumulates.
    for sign in [-1,1]:
        coords=[(sign*.020,top-.050),(sign*.055,top-.035),
                (sign*half*.77,top-.069),(sign*half*.69,bottom+.061),
                (sign*.048,bottom+.036)]
        points=[]
        for a,b in zip(coords,coords[1:]):
            points.extend(sample(a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t,.0035)
                          for t in [0,.25,.5,.75])
        points.append(sample(*coords[-1],.0035))
        g.tube(name+' / chest inset channel',points,.0011,dark,rigid='Spine2')
        for k in range(3 if heavy else 2):
            y=top-.073-k*.012
            points=[sample(sign*(.027+.020*t),y-.005*t,.004) for t in [0,.5,1]]
            g.tube(name+' / flush vent slit',points,.0013,dark,rigid='Spine2')
        for x,y in [(sign*half*.77,top-.075),(sign*half*.58,bottom+.035)]:
            g.rivet(sample(x,y,.003),Vector((0,0,1)),.0027,metal,dark)
    # Three small identity bars at the sternum; no separate projecting clasp.
    for x in [-.005,0,.005]:
        g.tube(name+' / inset identity bar',
               [sample(x,bottom+.071,.0035),sample(x,bottom+.082,.0035)],.001,signal,rigid='Spine2')
    # Fasteners generated by the shared helper use the same rigid attachment.
    for o in g.objects[start:]:
        o.vertex_groups.clear()
        group=o.vertex_groups.new(name=g.names['mixamorigSpine2'])
        group.add(list(range(len(o.data.vertices))),1,'REPLACE')
    # Geometric clearance and smooth-profile assertions protect the design datum.
    for i in range(1,20):
        y=bottom+height*i/20
        for u in [-.7,-.35,0,.35,.7]:
            assert sample(half*u,y).z >= g.front(half*u,y,1,0)[2]+(.004 if light else .010)
